-- BCB-MIGRATION-OWNER: app_object_owner
-- TEMPORARY LOCAL MIGRATION NUMBER 0031
--
-- Решение владельца 19.08: «Показ файла, пока делается миниатюра — но только после конвертации».
--
-- До этой миграции на строке `media_files` не было ни одного факта, по которому UI мог бы отличить
-- «байты по s3_key — это то, что закодировал наш энкодер» от «байты по s3_key — это то, что прислал
-- пользователь». Признаки, которые выглядят как ответ, ответом не являются:
--   * `s3_key LIKE '%/standard.webp'` — это соглашение об имени, а не факт о байтах;
--   * `mime_type = 'image/webp'` — пользователь имеет полное право загрузить WebP, который никогда
--     не переупаковывался;
--   * `preview_status = 'ready'` — говорит о миниатюре, а не о перекодировании, и для видео
--     выставляется без всякого перекодирования исходника.
--
-- Показывать неперекодированный файл нельзя (SECURITY_CANON §5: переупаковка — единственный
-- оставшийся рычаг после отказа от антивируса). Поэтому нужен собственный столбец-факт.
--
-- `standard_rendition_at` пишет ровно один код — тот же UPDATE воркера, который переставляет
-- `s3_key` на `media/<id>/standard.webp` (apps/webapp/src/infra/repos/mediaPreviewWorker.ts,
-- applyStandardImageRendition). Значение NOT NULL означает: объект по текущему `s3_key` — вывод
-- нашего энкодера, записанный в этот момент.
--
-- Бэкфилла НЕТ и быть не может. Все существующие строки загружены до появления шага
-- перекодирования, их `s3_key` указывает на исходную загрузку пользователя. NULL для них —
-- не «неизвестно», а «не перекодировано»; они обязаны и дальше показывать заглушку.
--
-- Индекс не нужен: столбец читается вместе со строкой по первичному ключу и не участвует
-- ни в WHERE, ни в ORDER BY ни на одном нагруженном пути.
--
-- Владелец шага — `app_object_owner`: SCHEME §обычные объекты, «стабильное владение ordinary
-- application objects и выполнение их DDL». Это первая post-B0 миграция, меняющая структуру
-- обычной таблицы, а не тело definer-функции, поэтому маркер не seam-owner.

ALTER TABLE public.media_files
  ADD COLUMN IF NOT EXISTS standard_rendition_at timestamptz;

COMMENT ON COLUMN public.media_files.standard_rendition_at IS
  'Момент, когда объект по s3_key был заменён выводом нашего энкодера (стандартный рендишн, SECURITY_CANON §5). NULL = не перекодировано, показывать файл нельзя.';
