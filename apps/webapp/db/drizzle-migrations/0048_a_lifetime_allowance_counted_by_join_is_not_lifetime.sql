-- Решение владельца 19.08, дословно: «Клинике дается ОДНА смена слаг самостоятельно (за весь период
-- жизни) - остальное через админа только если сами напишут в поддержку». «За весь период жизни»
-- значит, что израсходованное право не имеет права вернуться НИКОГДА и ни от какого стороннего
-- события.
--
-- Как оно возвращалось. Признак «эту смену сделала сама клиника» не хранился — он ВЫЧИСЛЯЛСЯ каждый
-- раз соединением события с текущим членством (`pgClinicDirectory.getSlugManagementState`,
-- INNER JOIN на `be_organization_members`). Членство удаляется каскадом от `platform_users`
-- (`be_organization_members_platform_user_id_fkey ... ON DELETE CASCADE`), а сама событийная таблица
-- только дозаписывается. Значит удаление аккаунта того сотрудника, который менял адрес, — обычная
-- будущая операция «удалить пользователя» — молча превращает израсходованное право в неизрасходованное.
-- Ни клиника, ни поддержка этого не увидят: счётчик просто станет другим.
--
-- Замер 19.08 на DEV (`bcb_webapp_dev`): 2 строки в `organization_slug_rename_events`; связь события
-- с актором держится ТОЛЬКО через `actor_platform_user_id`, отдельного признака инициатора нет.
--
-- Чинится штампом: факт ставится НА СОБЫТИЕ в момент записи и после этого не зависит ни от чего
-- внешнего. Производного счётчика-колонки на организации по-прежнему нет намеренно — источник истины
-- остаётся один, событийная таблица.
--
-- DEFAULT намеренно ограничительный. Забытый штамп должен ТРАТИТЬ право, а не выдавать бесконечные
-- смены: ошибка в сторону «клиника обратится в поддержку» обратима, ошибка в сторону «лимита нет»
-- необратима и незаметна.
--
-- Отдельного индекса на колонку нет сознательно. Единственное чтение —
-- `WHERE organization_id = $1 AND initiated_by = 'clinic'`; ведущий столбец уже покрыт
-- `idx_organization_slug_rename_events_org_created`, а число строк на организацию ограничено самим
-- правилом (одна самостоятельная смена плюс редкие админские). Второй индекс с тем же ведущим
-- столбцом дал бы стоимость записи без выигрыша чтения.

-- Бэкфилл существующих строк — это сам `DEFAULT 'clinic'` в строке ниже, и отдельного `UPDATE`
-- здесь НЕТ намеренно. `ADD COLUMN … DEFAULT` — это DDL: оно проставляет значение всем уже
-- существующим строкам разом, не зависит от RLS, не проходит через триггеры уровня строки и
-- выполняется одинаково на пустой и на непустой таблице. Повторный прогон миграции по этой
-- причине не может переписать ни одного штампа: переписывать нечем.
--
-- Прежняя редакция дописывала сюда безусловный `UPDATE … SET initiated_by = CASE WHEN EXISTS
-- (…членство…)`. Он снят, и каждая из трёх причин достаточна сама по себе:
--
-- 1. Мигратор применяет по водяному знаку `created_at`, и пока строки в леджере нет, миграция
--    остаётся pending. Безусловный `UPDATE` без `WHERE` при повторном прогоне пересчитал бы уже
--    проставленные штампы ТЕМ САМЫМ соединением с членством, ради устранения которого написана эта
--    миграция: сотрудник, менявший адрес, уволен → членство удалено каскадом → штамп переезжает в
--    'platform_admin' → клиника молча получает ВТОРУЮ пожизненную смену. Ровно та поломка, которую
--    миграция закрывает, только отложенная на один прогон.
-- 2. Направление ошибки. Единственное, что этот `UPDATE` мог изменить, — перевести строку из
--    'clinic' в 'platform_admin', то есть ВЕРНУТЬ израсходованное право. Это ровно та сторона,
--    которая абзацем выше названа необратимой и незаметной.
-- 3. Он и не работал. Statement с маркером `BCB-MIGRATION-OWNER` исполняется от владельца объекта
--    (`app_object_owner`), а на таблице стоит FORCE RLS без единой permissive-политики для этой
--    роли — политики есть только у `app_staff` и `app_seam_public_slug_owner`. DML владельца видит
--    ноль строк. Замер 19.08 на `bcb_webapp_dev` при двух реальных строках в таблице:
--    `SET ROLE app_object_owner; SELECT count(*) FROM public.organization_slug_rename_events` → 0,
--    и `bash deploy/host/migrate-dev.sh --preflight` печатает на этом statement `UPDATE 0`.
--    Сверх того, любой UPDATE по этой таблице отбивает append-only триггер
--    `app.guard_organization_slug_rename_event_mutation`.
--
-- Что теряется — измерено, а не оценено. На `bcb_webapp_dev` две строки, и у обеих актор
-- по-прежнему состоит в своей организации: соединение дало бы им 'clinic', то есть то же, что и
-- DEFAULT. На `bersoncarebot_test` строк в таблице нет вовсе. Ни одной строки ни на одной целевой
-- базе снятие бэкфилла не меняет.
