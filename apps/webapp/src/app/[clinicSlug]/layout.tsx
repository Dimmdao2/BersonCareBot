import type { ReactNode } from 'react';
import '../styles/patient.css';

/**
 * Оболочка публичного дерева клиники `/{clinic}` — визитка, запись, страница специалиста.
 *
 * Зачем она вообще появилась. После разворота адреса (владелец 19.08: «должно быть не
 * domain/booking/clinic, а domain/clinic/booking») канонический вход клиники уехал из `/book/**`
 * сюда, а тема пациента осталась там: `app/book/layout.tsx` подключает `styles/patient.css`, и
 * только он. Страницы этого дерева при этом собраны из пациентских примитивов, которые читают
 * `--patient-*` переменные, — без таблицы стилей переменные пусты, и `border-[var(--patient-border)]`
 * вырождается в чёрную рамку, а градиент секции — в серую заливку. Владелец 12.09 смотрел ровно
 * это: голая коробка вместо оформленной страницы записи.
 *
 * Почему отдельный layout, а не импорт в каждую страницу: дерево растёт (визитка, запись,
 * специалист, и дальше), и импорт в странице легко забыть — оболочка же применяется ко всему
 * поддереву по построению. Маршрут выдачи медиа `/{clinic}/media/[id]` — route handler, layout на
 * него не распространяется и ничего ему не добавляет.
 */
export default function ClinicPublicLayout({ children }: Readonly<{ children: ReactNode }>) {
  return <div className="min-h-[100dvh] bg-background text-foreground">{children}</div>;
}
