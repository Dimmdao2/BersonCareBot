/**
 * Отказ ЧТЕНИЯ визитки — не «клиники нет».
 *
 * Разница, ради которой этот класс существует (план §3.3): «такой клиники нет» и «прочитать не
 * удалось» выглядят на экране одинаково, если их не развести здесь. Первое — 404 намеренно:
 * различать наружу значило бы дать анониму перечислять клиники. Второе обязано быть слышным, то
 * есть отдавать код ошибки, а не 200 с вежливым текстом.
 *
 * ⚠️ Отдаётся 500, а не 503. Серверный компонент Next.js не умеет назначать HTTP-статус: 404 даёт
 * `notFound()`, всё остальное — только через границу ошибки, а она фиксирована на 500. Отдавать
 * 200 с текстом «временно недоступна» нельзя: это ровно ложная запись о готовности — мониторинг
 * и поисковик считают страницу здоровой. 503 против 500 — расхождение с планом, названное вслух,
 * а не молча смягчённое требование.
 */
export class ClinicCardUnavailableError extends Error {
  constructor(readonly slug: string) {
    super('clinic_public_card_unavailable');
    this.name = 'ClinicCardUnavailableError';
  }
}
