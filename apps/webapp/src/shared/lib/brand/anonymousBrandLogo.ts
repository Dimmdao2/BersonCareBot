import { orgAppIconUrl } from '@/shared/lib/brand/orgAppIcon';

/**
 * Знак клиники для экранов БЕЗ СЕССИИ — вход, приглашение, всё, что человек видит до логина.
 *
 * Зачем отдельная функция, хотя у бренда уже есть `logoUrl`. `logoUrl` в анонимной проекции
 * поверхности — это адрес вида `/api/media/<id>`, а эта дверь сессионная: анониму она отвечает
 * `401`. Получается ловушка — проекция называется анонимно-безопасной и несёт адрес, который
 * анониму не открыть. Ровно на неё 15.09 наступил я сам: поставил `logoUrl` в шапку пациентского
 * входа, и на проде клиника получила битую картинку вместо своего знака. Владелец: «задумано так,
 * что для публичных материалов вход без логина».
 *
 * Публичная дверь для знака в системе уже есть — `/api/brand/app-icon/<media id>/<размер>.png`.
 * Она не спрашивает ни сессию, ни базу: адрес полностью задаёт ключ объекта, а объект существует
 * только там, где сотрудник клиники сам поставил эту иконку своей организации. Поэтому знак на
 * анонимном экране строится ТОЛЬКО отсюда.
 *
 * Иконки нет — возвращаем `null`, и экран показывает имя организации. Пустое место на месте знака
 * или битая картинка хуже, чем честное имя.
 */
export function anonymousBrandLogoUrl(
  brand: { appIconMediaId?: string } | null | undefined,
): string | null {
  const mediaId = brand?.appIconMediaId?.trim();
  if (!mediaId) return null;
  try {
    return orgAppIconUrl(mediaId, '192');
  } catch {
    return null;
  }
}
