/**
 * Что наш энкодер вообще производит для этого типа файла — единственная формулировка.
 *
 * Зачем правило названо отдельно: стены выдачи М7 держатся на утверждении «нет нашего вывода —
 * наружу ничего не идёт». Оно верно РОВНО для тех типов, у которых наш вывод бывает: картинка
 * получает стандартный WebP, видео — HLS. Для документа и аудио мы не производим ничего и не будем,
 * поэтому «рендишн не готов» у них не временное состояние, а вечное: заглушка «файл готовится» там
 * никогда не сменится файлом, а сам загруженный объект И ЕСТЬ то, что нужно отдать.
 *
 * Решение владельца 11.09, под которое делались стены, дословно про «картинка готовится или видео
 * готовится» — то есть про эти два типа. Этот модуль не даёт правилу расползтись на остальные.
 */
export type MediaEncoderOutput = 'standard_image' | 'hls_video' | 'none';

export function encoderOutputFor(mimeType: string | null | undefined): MediaEncoderOutput {
  const lower = (mimeType ?? '').trim().toLowerCase();
  if (lower.startsWith('image/')) return 'standard_image';
  if (lower.startsWith('video/')) return 'hls_video';
  return 'none';
}
