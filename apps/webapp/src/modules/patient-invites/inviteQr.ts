import QRCode from 'qrcode';

/**
 * QR-код приглашения рисуется НА СЕРВЕРЕ и уезжает в браузер готовой картинкой.
 *
 * Владелец 10.09.2026: «кнопка скопировать и показать QR-код… QR-код открывается в модалке
 * крупно, по центру экрана». Живой сценарий — специалист держит экран, человек наводит телефон,
 * поэтому картинка должна быть уже на странице к моменту нажатия, а не подгружать библиотеку.
 *
 * SVG, а не PNG: он весит полтора килобайта и масштабируется под любой экран без размытия.
 * Отдаётся `data:`-ссылкой под `<img>`, а не разметкой: картинка в `<img>` не исполняет скриптов и
 * не попадает в DOM страницы, поэтому вставлять её не приходится через `dangerouslySetInnerHTML`.
 */
export async function renderInviteQrDataUri(url: string): Promise<string> {
  const svg = await QRCode.toString(url, {
    type: 'svg',
    // M выдерживает блик и палец на экране, но не раздувает сетку так, как это делает H.
    errorCorrectionLevel: 'M',
    margin: 1,
  });
  return `data:image/svg+xml;base64,${Buffer.from(svg, 'utf8').toString('base64')}`;
}
