import { getServerRuntimeBool } from '@/modules/system-settings/configAdapter';

/**
 * Единственное место, где читается платформенный переключатель второго фактора
 * (`auth_2fa_enabled`, админка → Вход). Оба потребителя — страж страниц
 * (`isRestrictedStaffSecuritySession`) и решение о переходе после входа — обязаны спрашивать
 * здесь, иначе переключатель становится декорацией в одной половине системы: страж пускает, а
 * вход всё равно уводит на настройку фактора.
 *
 * ⛔ Сбой чтения НЕ трактуется никак — ни как «выключено», ни как «включено». Прежняя редакция
 * этого файла делала `catch { return false }`, и слепой аудит 01.08 воспроизвёл последствие живьём:
 * при недоступном аксессоре персонал молча проходил на `/app/doctor` с кодом 200, то есть политика
 * подменялась без единого следа. Решение владельца 01.08 дословно: «База моргнула — мы ничего не
 * требуем. Мы просто не пускаем пока не поднимется». Ужесточать тоже нельзя: включённый вслепую
 * второй фактор запирает весь персонал, у кого он не заведён (инцидент 25.07, описан в
 * `app-layer/guards/requireRole.ts`). Поэтому ошибка идёт наверх, и маршрут отвечает отказом.
 */
export async function platformRequiresStaffTwoFactor(): Promise<boolean> {
  return getServerRuntimeBool('auth_2fa_enabled');
}
