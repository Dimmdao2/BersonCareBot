/**
 * Куда физически ложится объект. Тот же словарь, что и у webapp: воркер получает значение в
 * наряде и не выбирает его сам.
 *
 * `library` — библиотека упражнений и медиа CMS. `patient` — файлы и видео пациентов.
 */
export type StorageTarget = 'library' | 'patient';

/**
 * Хранилище из наряда. Колонка `media_files.storage_target` объявлена NOT NULL без умолчания,
 * поэтому у ЛЮБОЙ живой строки значение есть, и отсутствие его здесь означает не «старая строка»,
 * а расхождение версий или запрос, забывший выбрать колонку.
 *
 * Подставить в этом случае библиотеку — ровно то, что владелец запретил 06.09.2026: «если для
 * файлов пациентов мы забудем подставить назначение в каком-то куске кода, они загрузятся в
 * библиотеку. А это неправильно». Воркер ходит в хранилище на запись и на УДАЛЕНИЕ, так что
 * ошибка здесь дороже, чем упавший наряд. Поэтому отказ: наряд падает громко, цикл его логирует
 * и берёт следующий, а байты пациента не уезжают в чужой бакет.
 */
export function parseStorageTarget(value: unknown): StorageTarget {
  if (value === 'patient' || value === 'library') return value;
  throw new Error(`storage_target_missing_on_row: ${JSON.stringify(value)}`);
}
