#!/usr/bin/env bash
# Единственный ответ на вопрос «в какую базу ходит рантайм прода».
#
# Вопрос задают минимум двое: обновление описателей порт-контекста и связывание видео с настройками
# приложения. Второй такой же вывод в другом файле — это не дубль кода, это будущее расхождение:
# после переименования базы один из двух неизбежно остался бы со старым именем и молча писал бы не туда.
#
# Имя базы НЕ задаётся здесь константой. Оно читается из тех же env-файлов, по которым в базу ходит
# приложение, и из ВСЕХ строк подключения сразу: webapp ходит тремя ролями, api — четвёртой, общего
# ключа `DATABASE_URL` в этих файлах нет вовсе. Требование, чтобы все четыре назвали одну базу, — это
# заодно проверка целостности: забытая после переименования строка останавливает работу здесь, а не
# проявляется позже отказом половины рантайма.
#
# Использование:
#   . "$(dirname "$0")/runtime-database.sh"
#   runtime_database        # печатает имя базы, падает с внятной причиной
#   runtime_environment DB  # печатает окружение декларации для этого имени

therapysto_env_dir() { echo "${THERAPYSTO_ENV_DIR:-/etc/therapysto/env}"; }

runtime_database() {
  local env_dir; env_dir=$(therapysto_env_dir)
  local webapp="$env_dir/webapp.prod" api="$env_dir/api.prod"
  [ -r "$webapp" ] && [ -r "$api" ] || {
    echo "runtime-database: не читаются $webapp и $api" >&2; return 1; }
  local dbs
  mapfile -t dbs < <(cat "$webapp" "$api" |
    grep -oE "postgres(ql)?://[^'\" ]+" |
    sed -E 's#^.*/([A-Za-z0-9_]+)(\?.*)?$#\1#' | sort -u)
  [ "${#dbs[@]}" -gt 0 ] || {
    echo "runtime-database: в env-файлах рантайма нет ни одной строки подключения postgres://" >&2; return 1; }
  [ "${#dbs[@]}" -eq 1 ] || {
    echo "runtime-database: рантайм ходит в РАЗНЫЕ базы: ${dbs[*]} — сначала приведите env-файлы к одной" >&2; return 1; }
  printf '%s\n' "${dbs[0]}"
}

# Окружение выводится из имени базы, а не задаётся отдельно: два независимых значения рано или поздно
# разъезжаются. Незнакомое имя — отказ, а не подстановка умолчания: тихо выдать одному окружению
# каталог возможностей другого хуже, чем не выполниться.
runtime_environment() {
  case "${1:-}" in
    therapysto_prod) echo prod ;;
    bersoncarebot_test) echo test ;;
    *) echo "runtime-database: база '${1:-}' не объявлена в декларации прав — добавьте её туда, а не сюда" >&2; return 1 ;;
  esac
}

# Мигратор — тоже имя, и тоже одно на всю машину. Он живёт здесь, а не в вызывающем скрипте, по той
# же причине: третье место, знающее имена ролей, разъедется при следующем переименовании.
runtime_migrator() {
  case "${1:-}" in
    prod) echo therapysto_prod_migrator ;;
    test) echo bcb_test_migrator ;;
    *) echo "runtime-database: не знаю мигратора для окружения '${1:-}'" >&2; return 1 ;;
  esac
}
