export function getAppPatientGrantTables({ descriptors = buildRlsDescriptors() } = {}) {
  const patientScopedTables = Array.from(descriptors.values())
    .filter(
      (descriptor) =>
        descriptor.patientColumn ||
        descriptor.patientChain ||
        descriptor.patientConditional ||
        descriptor.patientConditionalChain ||
        descriptor.patientPolymorphic,
    )
    .map((descriptor) => ({
      qualifiedName: descriptor.table,
      privileges: patientScopedPrivilegeOverrides.get(descriptor.table) ?? "SELECT",
    }));

  const allTables = [...patientScopedTables, ...appPatientBootstrapTables];

  return allTables
    .map((table) => ({ ...splitQualifiedName(table.qualifiedName), ...table }))
    .sort((left, right) => left.qualifiedName.localeCompare(right.qualifiedName));
}

function sqlIdent(name) {
  return `"${name.replaceAll('"', '""')}"`;
}

function renderGrantTableValues(tables, { withPrivileges }) {
  return tables
    .map((table, index) => {
      const row = withPrivileges
        ? `  (${sqlString(table.schemaName)}, ${sqlString(table.tableName)}, ${sqlString(table.privileges)})`
        : `  (${sqlString(table.schemaName)}, ${sqlString(table.tableName)})`;
      return `${row}${index === tables.length - 1 ? ";" : ","}`;
    })
    .join("\n");
}

function sqlString(value) {
  return `'${value.replaceAll("'", "''")}'`;
}

export function renderP05bGrantsSql({ descriptors = buildRlsDescriptors() } = {}) {
  const staffTables = getAppStaffGrantTables();
  const patientTables = getAppPatientGrantTables({ descriptors });
  const staffSchemas = Array.from(new Set(staffTables.map((table) => table.schemaName))).sort();
  const patientSchemas = Array.from(new Set(patientTables.map((table) => table.schemaName))).sort();

  return `-- P0.5b-v2 / B5 (docs/_TODO/SAAS_FOUNDATION/LOG.md, taskdb #655): dormant table-level GRANTs
-- for the fixed app_staff / app_patient roles created by
-- deploy/postgres/p0-5b-role-split-staff-patient.sql.
--
-- Generated by docs/_TODO/SAAS_FOUNDATION/scripts/p0-5b-grants-sql.mjs.
-- Do not edit the generated grant lists by hand; update the generator and regenerate. See that
-- script's header + docs/_TODO/SAAS_FOUNDATION/P0_5B_GRANTS.md for the full rationale (why each
-- table got SELECT-only vs a write grant, and which BOOTSTRAP tables were deliberately excluded).
--
-- Purpose:
--   - app_staff: the FULL runtime DML surface -- ${staffTables.length} tables (SCOPED + BOOTSTRAP +
--     INFRA + LEGACY + TELEMETRY, excluding the 4 pure migration-bookkeeping tables the migrator role
--     alone touches).
--   - app_patient: ONLY the patient-facing surface -- ${patientTables.length} tables (the patient-owned
--     SCOPED set + a small confirmed BOOTSTRAP identity/settings subset). SELECT by default;
--     INSERT/UPDATE/DELETE added only where a patient-authenticated route/repo confirms the write.
--
-- Dormant boundary (same as p0-5b-role-split-staff-patient.sql):
--   - this script does not change application DATABASE_URL values or switch any runtime process to
--     either role;
--   - this script does not deploy, migrate, or enable new RLS enforcement;
--   - this script ONLY adds GRANTs to the two already-existing (dormant, no-credential) roles.
--
-- Requires app_staff/app_patient to already exist -- run p0-5b-role-split-staff-patient.sql first.
--
-- No psql variables required (role names are fixed) -- invoke directly:
--   psql '<database-url>' -f deploy/postgres/p0-5b-grants.sql
--
-- Rollback:
--   Re-run with -v p0_5b_grants_down=1. Revokes ALL privileges this script could have granted from
--   both roles (REVOKE ALL is idempotent/safe even for a privilege subset). Does not drop the roles
--   themselves -- that remains p0-5b-role-split-staff-patient.sql's job.

\\set ON_ERROR_STOP on
\\pset pager off

SELECT (
  EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'app_staff')
  AND EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'app_patient')
)::int AS p0_5b_grants_roles_exist \\gset

\\if :p0_5b_grants_roles_exist
\\else
\\echo 'FATAL: app_staff/app_patient must already exist -- run p0-5b-role-split-staff-patient.sql first.'
SELECT 1 / 0 AS p0_5b_grants_abort;
\\endif

CREATE TEMP TABLE p0_5b_staff_grant_tables (
  schema_name name NOT NULL,
  table_name name NOT NULL,
  PRIMARY KEY (schema_name, table_name)
);
-- Session-scoped TEMP table (NOT ON COMMIT DROP -- psql autocommit; see p0-5-role-split.sql's note
-- of the same shape, found live 2026-07-11).

INSERT INTO p0_5b_staff_grant_tables (schema_name, table_name)
VALUES
${renderGrantTableValues(staffTables, { withPrivileges: false })}

CREATE TEMP TABLE p0_5b_patient_grant_tables (
  schema_name name NOT NULL,
  table_name name NOT NULL,
  privileges text NOT NULL,
  PRIMARY KEY (schema_name, table_name)
);

INSERT INTO p0_5b_patient_grant_tables (schema_name, table_name, privileges)
VALUES
${renderGrantTableValues(patientTables, { withPrivileges: true })}

\\if :{?p0_5b_grants_down}
\\echo 'P0.5b grants DOWN: revoking app_staff/app_patient table+sequence+schema grants.'

SELECT format('REVOKE ALL PRIVILEGES ON TABLE %I.%I FROM app_staff', schema_name, table_name)
FROM p0_5b_staff_grant_tables
WHERE EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'app_staff')
ORDER BY schema_name, table_name
\\gexec

SELECT format('REVOKE ALL PRIVILEGES ON TABLE %I.%I FROM app_patient', schema_name, table_name)
FROM p0_5b_patient_grant_tables
WHERE EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'app_patient')
ORDER BY schema_name, table_name
\\gexec

SELECT format('REVOKE USAGE, SELECT ON SEQUENCE %I.%I FROM app_staff', seq_ns.nspname, seq.relname)
FROM pg_class seq
JOIN pg_namespace seq_ns ON seq_ns.oid = seq.relnamespace
JOIN pg_depend dep ON dep.objid = seq.oid AND dep.deptype = 'a'
JOIN pg_class tbl ON tbl.oid = dep.refobjid
JOIN pg_namespace tbl_ns ON tbl_ns.oid = tbl.relnamespace
JOIN p0_5b_staff_grant_tables targets ON targets.schema_name = tbl_ns.nspname AND targets.table_name = tbl.relname
WHERE seq.relkind = 'S'
  AND EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'app_staff')
ORDER BY seq_ns.nspname, seq.relname
\\gexec

SELECT format('REVOKE USAGE, SELECT ON SEQUENCE %I.%I FROM app_patient', seq_ns.nspname, seq.relname)
FROM pg_class seq
JOIN pg_namespace seq_ns ON seq_ns.oid = seq.relnamespace
JOIN pg_depend dep ON dep.objid = seq.oid AND dep.deptype = 'a'
JOIN pg_class tbl ON tbl.oid = dep.refobjid
JOIN pg_namespace tbl_ns ON tbl_ns.oid = tbl.relnamespace
JOIN p0_5b_patient_grant_tables targets ON targets.schema_name = tbl_ns.nspname AND targets.table_name = tbl.relname
WHERE seq.relkind = 'S'
  AND EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'app_patient')
ORDER BY seq_ns.nspname, seq.relname
\\gexec

${staffSchemas.map((schema) => `SELECT format('REVOKE USAGE ON SCHEMA %I FROM app_staff', '${schema}') WHERE EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'app_staff') \\gexec`).join("\n")}

${patientSchemas.map((schema) => `SELECT format('REVOKE USAGE ON SCHEMA %I FROM app_patient', '${schema}') WHERE EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'app_patient') \\gexec`).join("\n")}

\\echo 'P0.5b grants DOWN complete.'
\\else
\\echo 'P0.5b grants UP: app_staff full runtime surface, app_patient curated patient-facing surface.'

${staffSchemas.map((schema) => `GRANT USAGE ON SCHEMA ${sqlIdent(schema)} TO app_staff;`).join("\n")}
${patientSchemas.map((schema) => `GRANT USAGE ON SCHEMA ${sqlIdent(schema)} TO app_patient;`).join("\n")}

SELECT format('GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE %I.%I TO app_staff', schema_name, table_name)
FROM p0_5b_staff_grant_tables
ORDER BY schema_name, table_name
\\gexec

SELECT format('GRANT %s ON TABLE %I.%I TO app_patient', privileges, schema_name, table_name)
FROM p0_5b_patient_grant_tables
ORDER BY schema_name, table_name
\\gexec

SELECT format('GRANT USAGE, SELECT ON SEQUENCE %I.%I TO app_staff', seq_ns.nspname, seq.relname)
FROM pg_class seq
JOIN pg_namespace seq_ns ON seq_ns.oid = seq.relnamespace
JOIN pg_depend dep ON dep.objid = seq.oid AND dep.deptype = 'a'
JOIN pg_class tbl ON tbl.oid = dep.refobjid
JOIN pg_namespace tbl_ns ON tbl_ns.oid = tbl.relnamespace
JOIN p0_5b_staff_grant_tables targets ON targets.schema_name = tbl_ns.nspname AND targets.table_name = tbl.relname
WHERE seq.relkind = 'S'
ORDER BY seq_ns.nspname, seq.relname
\\gexec

SELECT format('GRANT USAGE, SELECT ON SEQUENCE %I.%I TO app_patient', seq_ns.nspname, seq.relname)
FROM pg_class seq
JOIN pg_namespace seq_ns ON seq_ns.oid = seq.relnamespace
JOIN pg_depend dep ON dep.objid = seq.oid AND dep.deptype = 'a'
JOIN pg_class tbl ON tbl.oid = dep.refobjid
JOIN pg_namespace tbl_ns ON tbl_ns.oid = tbl.relnamespace
JOIN p0_5b_patient_grant_tables targets ON targets.schema_name = tbl_ns.nspname AND targets.table_name = tbl.relname
WHERE seq.relkind = 'S'
ORDER BY seq_ns.nspname, seq.relname
\\gexec

-- Re-assert the B4-roles-1 security invariant: issuing a large batch of GRANTs here must not
-- accidentally create or reveal a membership path from app_patient to app_staff. Same pg_has_role
-- transitive check as p0-5b-role-split-staff-patient.sql and the p0-5-role-split.sql fix above.
SELECT (NOT pg_has_role('app_patient', 'app_staff', 'MEMBER'))::int AS p0_5b_grants_patient_not_staff_ok \\gset

\\if :p0_5b_grants_patient_not_staff_ok
\\else
\\echo 'FATAL: P0.5b grants -- app_patient must NOT be a member of app_staff (directly or transitively).'
SELECT 1 / 0 AS p0_5b_grants_abort;
\\endif

\\echo 'P0.5b grants UP complete: app_staff ${staffTables.length} tables, app_patient ${patientTables.length} tables.'
\\endif
`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  process.stdout.write(renderP05bGrantsSql());
}
