// P0.5b-v2 / B5 (docs/_TODO/SAAS_FOUNDATION/LOG.md, taskdb #655): dormant table-level GRANTs for the
// fixed app_staff / app_patient roles created by deploy/postgres/p0-5b-role-split-staff-patient.sql.
//
// Two independent grant sets, deliberately built from two different sources:
//   - app_staff: MECHANICAL, derived straight from tiers-218.tsv (readTierRows()) -- every tier
//     except the 4 pure migration-bookkeeping tables (touched only by the migrator role, never by a
//     running app process). This is the FULL runtime surface: SCOPED (patient-wall RLS applies,
//     app_staff bypasses via app.is_staff()) + BOOTSTRAP (identity/settings) + INFRA (queues/
//     outboxes the webapp/integrator/worker/scheduler/media processes read and write every request)
//     + LEGACY (frozen Rubitime-era tables still read by legacy sync paths) + TELEMETRY (analytics
//     rollups). Cross-model audit finding #3 in R2_MVP_MASTER_CHECKLIST.md: the OLD single-role
//     p0-5-role-split.sql grants only SCOPED+BOOTSTRAP, so the runtime would get "permission denied"
//     on every INFRA/LEGACY/TELEMETRY table the moment a role-scoped connection replaced the
//     superuser/owner connection apps currently use -- this closes that gap for app_staff.
//   - app_patient: CURATED, NOT mechanically derived. The candidate table set is exactly the 102
//     patient-owned SCOPED tables (buildRlsDescriptors() entries with patientColumn / patientChain /
//     patientConditional / patientConditionalChain / patientPolymorphic set) plus a small, explicitly
//     enumerated BOOTSTRAP identity/settings subset the patient PWA reads/writes for its OWN account.
//     Privileges per table are NOT uniform: SELECT is the default; INSERT/UPDATE/DELETE are added
//     ONLY where a patient-authenticated webapp route/repo was traced (2026-07-11 audit, this task)
//     confirming that the patient's OWN session (not staff, not a background worker under a
//     different service identity) performs that write. Every non-SELECT-only row below carries an
//     inline comment naming the confirming route/repo. Tables where the write path is staff-authored
//     content, a scheduler/worker side effect, or genuinely unconfirmed are left SELECT-only ON
//     PURPOSE (conservative default: a missing write grant surfaces loudly as "permission denied" in
//     B4-fanout's pre-flip process smoke; an EXCESS write grant would be a silent, hard-to-notice
//     privilege escalation). See P0_5B_GRANTS.md for the full table-by-table rationale and the
//     explicit "flagged for review" list of BOOTSTRAP tables deliberately NOT granted.
//
// Dormant boundary: identical to p0-5b-role-split-staff-patient.sql -- this file ONLY adds table/
// sequence/schema GRANTs to the two already-existing (dormant, no-credential) roles. No DATABASE_URL
// change, no runtime role switch, no RLS/policy change, no new migration.
//
// Generated by this script. Do not edit deploy/postgres/p0-5b-grants.sql by hand; update the tables
// below (or the tier artifacts, for the app_staff side) and regenerate:
//   node docs/_TODO/SAAS_FOUNDATION/scripts/p0-5b-grants-sql.mjs > deploy/postgres/p0-5b-grants.sql

import { buildRlsDescriptors, readTierRows } from "./rls-descriptor-model.mjs";

// Pure migration-bookkeeping tables: touched only by the migrator role (schema_migrations ledgers),
// never by a running webapp/integrator/worker/scheduler/media process. Excluding these from
// app_staff's INFRA grant is the "кроме чисто-миграционных" carve-out this task calls for.
const migrationOnlyTables = new Set([
  "drizzle.__drizzle_migrations",
  "integrator.schema_migrations",
  "public.schema_migrations",
  "public.webapp_schema_migrations",
]);

const appStaffGrantTiers = new Set(["SCOPED", "BOOTSTRAP", "INFRA", "LEGACY", "TELEMETRY"]);

function splitQualifiedName(qualifiedName) {
  const [schemaName, tableName, extra] = qualifiedName.split(".");

  if (!schemaName || !tableName || extra) {
    throw new Error(`Expected schema-qualified table name, got ${qualifiedName}`);
  }

  return { schemaName, tableName };
}

export function getAppStaffGrantTables() {
  return readTierRows()
    .filter((row) => appStaffGrantTiers.has(row.tier) && !migrationOnlyTables.has(row.table))
    .map((row) => ({ ...splitQualifiedName(row.table), qualifiedName: row.table, tier: row.tier }))
    .sort((left, right) => left.qualifiedName.localeCompare(right.qualifiedName));
}

