#!/usr/bin/env node

import { buildRlsDescriptors } from './rls-descriptor-model.mjs';

const grantTiers = new Set(['SCOPED', 'BOOTSTRAP']);

// These tables have dedicated privilege boundaries. Runtime settings use audience-specific roles;
// the staff-security vault is reachable only through self-scoped SECURITY DEFINER functions.
// Granting any of them to the generic legacy app role would bypass the reviewed split.
export const p05DedicatedRoleTables = new Set([
  'public.app_runtime_settings',
  'public.app_runtime_settings_audit',
  'public.staff_security_profiles',
]);

function sqlString(value) {
  return `'${value.replaceAll("'", "''")}'`;
}

export function getP05AppGrantTables({ descriptors = buildRlsDescriptors() } = {}) {
  return Array.from(descriptors.values())
    .filter(
      (descriptor) =>
        grantTiers.has(descriptor.tier) && !p05DedicatedRoleTables.has(descriptor.table),
    )
    .map((descriptor) => {
      const [schemaName, tableName, extra] = descriptor.table.split('.');

      if (!schemaName || !tableName || extra) {
        throw new Error(`Expected schema-qualified table name, got ${descriptor.table}`);
      }

      return {
        schemaName,
        tableName,
        tier: descriptor.tier,
        qualifiedName: descriptor.table,
      };
    })
    .sort((left, right) => left.qualifiedName.localeCompare(right.qualifiedName));
}

function renderGrantTableValues(tables) {
  return tables
    .map(
      (table, index) =>
        `  (${sqlString(table.schemaName)}, ${sqlString(table.tableName)}, ${sqlString(table.tier)})${
          index === tables.length - 1 ? ';' : ','
        }`,
    )
    .join('\n');
}

export function renderP05RoleSplitSql({ descriptors = buildRlsDescriptors() } = {}) {
  const grantTables = getP05AppGrantTables({ descriptors });

  return `-- P0.5 / B5 dormant DB role split.
-- Generated by docs/_TODO/SAAS_FOUNDATION/scripts/p0-5-role-split-sql.mjs.
-- Do not edit the generated grant list by hand; update the SaaS tier artifacts and regenerate.
--
-- Purpose:
--   - create/normalize an owner role and deploy-only migrator role with BYPASSRLS for DDL/backfills;
--   - create/normalize a non-owner application role with NOBYPASSRLS;
--   - grant the app role runtime DML on SCOPED and BOOTSTRAP tables only.
--
-- Dormant boundary:
--   - this script does not change application DATABASE_URL values;
--   - this script does not switch runtime processes to the app role;
--   - this script does not deploy, migrate, or enable new RLS enforcement.
--
-- Required psql variables:
--   - p0_5_owner_role
--   - p0_5_migrator_role
--   - p0_5_app_role
--
-- Example shape only, with operator-chosen role names:
--   psql '<database-url>' \\
--     -v p0_5_owner_role='<owner_role>' \\
--     -v p0_5_migrator_role='<migrator_role>' \\
--     -v p0_5_app_role='<app_role>' \\
--     -f deploy/postgres/p0-5-role-split.sql
--
-- Rollback:
--   Re-run with -v p0_5_down=1 and the same role variables. The down block revokes
--   grants/memberships and drops the roles only if PostgreSQL allows it. It intentionally
--   does not REASSIGN OWNED or DROP OWNED, because those are destructive ownership operations.

\\set ON_ERROR_STOP on
\\pset pager off

\\if :{?p0_5_owner_role}
\\else
\\echo 'FATAL: missing required psql variable p0_5_owner_role.'
SELECT 1 / 0 AS p0_5_abort;
\\endif

\\if :{?p0_5_migrator_role}
\\else
\\echo 'FATAL: missing required psql variable p0_5_migrator_role.'
SELECT 1 / 0 AS p0_5_abort;
\\endif

\\if :{?p0_5_app_role}
\\else
\\echo 'FATAL: missing required psql variable p0_5_app_role.'
SELECT 1 / 0 AS p0_5_abort;
\\endif

SELECT (
  length(:'p0_5_owner_role') > 0
  AND length(:'p0_5_migrator_role') > 0
  AND length(:'p0_5_app_role') > 0
  AND :'p0_5_owner_role' <> :'p0_5_migrator_role'
  AND :'p0_5_owner_role' <> :'p0_5_app_role'
  AND :'p0_5_migrator_role' <> :'p0_5_app_role'
)::int AS p0_5_role_names_valid \\gset

\\if :p0_5_role_names_valid
\\else
\\echo 'FATAL: P0.5 role names must be non-empty and distinct.'
SELECT 1 / 0 AS p0_5_abort;
\\endif

SELECT rolsuper::int AS p0_5_can_manage_roles
FROM pg_roles
WHERE rolname = current_user \\gset

\\if :p0_5_can_manage_roles
\\else
\\echo 'FATAL: P0.5 role split requires a superuser-capable executor because owner/migrator roles use BYPASSRLS.'
SELECT 1 / 0 AS p0_5_abort;
\\endif

CREATE TEMP TABLE p0_5_app_grant_tables (
  schema_name name NOT NULL,
  table_name name NOT NULL,
  tier text NOT NULL CHECK (tier IN ('SCOPED', 'BOOTSTRAP')),
  PRIMARY KEY (schema_name, table_name)
);
-- Session-scoped TEMP table (NOT ON COMMIT DROP): psql runs statements in autocommit, so
-- ON COMMIT DROP would drop the table immediately after CREATE, before the INSERT. It is
-- auto-dropped when the psql session ends. (Found by live scratch proof, 2026-07-11.)

INSERT INTO p0_5_app_grant_tables (schema_name, table_name, tier)
VALUES
${renderGrantTableValues(grantTables)}

\\if :{?p0_5_down}
\\echo 'P0.5 role split DOWN: revoking app grants and dropping roles when unused.'

SELECT format('REVOKE SELECT, INSERT, UPDATE, DELETE ON TABLE %I.%I FROM %I', schema_name, table_name, :'p0_5_app_role')
FROM p0_5_app_grant_tables
WHERE EXISTS (SELECT 1 FROM pg_roles WHERE rolname = :'p0_5_app_role')
ORDER BY schema_name, table_name
\\gexec

SELECT format('REVOKE USAGE, SELECT ON SEQUENCE %I.%I FROM %I', seq_ns.nspname, seq.relname, :'p0_5_app_role')
FROM pg_class seq
JOIN pg_namespace seq_ns ON seq_ns.oid = seq.relnamespace
JOIN pg_depend dep ON dep.objid = seq.oid AND dep.deptype = 'a'
JOIN pg_class tbl ON tbl.oid = dep.refobjid
JOIN pg_namespace tbl_ns ON tbl_ns.oid = tbl.relnamespace
JOIN p0_5_app_grant_tables targets ON targets.schema_name = tbl_ns.nspname AND targets.table_name = tbl.relname
WHERE seq.relkind = 'S'
  AND EXISTS (SELECT 1 FROM pg_roles WHERE rolname = :'p0_5_app_role')
ORDER BY seq_ns.nspname, seq.relname
\\gexec

SELECT format('REVOKE USAGE ON SCHEMA %I FROM %I', schema_name, :'p0_5_app_role')
FROM (SELECT DISTINCT schema_name FROM p0_5_app_grant_tables) schemas
WHERE EXISTS (SELECT 1 FROM pg_roles WHERE rolname = :'p0_5_app_role')
ORDER BY schema_name
\\gexec

SELECT format('REVOKE CONNECT ON DATABASE %I FROM %I', current_database(), :'p0_5_app_role')
WHERE EXISTS (SELECT 1 FROM pg_roles WHERE rolname = :'p0_5_app_role')
\\gexec

SELECT format('REVOKE %I FROM %I', :'p0_5_owner_role', :'p0_5_migrator_role')
WHERE EXISTS (SELECT 1 FROM pg_roles WHERE rolname = :'p0_5_owner_role')
  AND EXISTS (SELECT 1 FROM pg_roles WHERE rolname = :'p0_5_migrator_role')
\\gexec

SELECT format('REVOKE %I FROM %I', :'p0_5_owner_role', :'p0_5_app_role')
WHERE EXISTS (SELECT 1 FROM pg_roles WHERE rolname = :'p0_5_owner_role')
  AND EXISTS (SELECT 1 FROM pg_roles WHERE rolname = :'p0_5_app_role')
\\gexec

SELECT format('REVOKE %I FROM %I', :'p0_5_migrator_role', :'p0_5_app_role')
WHERE EXISTS (SELECT 1 FROM pg_roles WHERE rolname = :'p0_5_migrator_role')
  AND EXISTS (SELECT 1 FROM pg_roles WHERE rolname = :'p0_5_app_role')
\\gexec

SELECT format('DROP ROLE %I', :'p0_5_app_role')
WHERE EXISTS (SELECT 1 FROM pg_roles WHERE rolname = :'p0_5_app_role')
\\gexec

SELECT format('DROP ROLE %I', :'p0_5_migrator_role')
WHERE EXISTS (SELECT 1 FROM pg_roles WHERE rolname = :'p0_5_migrator_role')
\\gexec

SELECT format('DROP ROLE %I', :'p0_5_owner_role')
WHERE EXISTS (SELECT 1 FROM pg_roles WHERE rolname = :'p0_5_owner_role')
\\gexec

\\echo 'P0.5 role split DOWN complete.'
\\else
\\echo 'P0.5 role split UP: creating roles and granting SCOPED/BOOTSTRAP app DML.'

SELECT format('CREATE ROLE %I NOLOGIN BYPASSRLS', :'p0_5_owner_role')
WHERE NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = :'p0_5_owner_role')
\\gexec

SELECT format('CREATE ROLE %I LOGIN BYPASSRLS', :'p0_5_migrator_role')
WHERE NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = :'p0_5_migrator_role')
\\gexec

SELECT format('CREATE ROLE %I LOGIN NOBYPASSRLS', :'p0_5_app_role')
WHERE NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = :'p0_5_app_role')
\\gexec

ALTER ROLE :"p0_5_owner_role" NOLOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION BYPASSRLS;
ALTER ROLE :"p0_5_migrator_role" LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION BYPASSRLS;
ALTER ROLE :"p0_5_app_role" LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS;

GRANT :"p0_5_owner_role" TO :"p0_5_migrator_role";
REVOKE :"p0_5_owner_role" FROM :"p0_5_app_role";
REVOKE :"p0_5_migrator_role" FROM :"p0_5_app_role";

SELECT format('GRANT CONNECT ON DATABASE %I TO %I', current_database(), :'p0_5_owner_role') \\gexec
SELECT format('GRANT CONNECT ON DATABASE %I TO %I', current_database(), :'p0_5_migrator_role') \\gexec
SELECT format('GRANT CONNECT ON DATABASE %I TO %I', current_database(), :'p0_5_app_role') \\gexec

SELECT format('GRANT USAGE, CREATE ON SCHEMA %I TO %I', schema_name, :'p0_5_owner_role')
FROM (SELECT DISTINCT schema_name FROM p0_5_app_grant_tables) schemas
ORDER BY schema_name
\\gexec

SELECT format('GRANT USAGE ON SCHEMA %I TO %I', schema_name, :'p0_5_app_role')
FROM (SELECT DISTINCT schema_name FROM p0_5_app_grant_tables) schemas
ORDER BY schema_name
\\gexec

SELECT format('GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE %I.%I TO %I', schema_name, table_name, :'p0_5_app_role')
FROM p0_5_app_grant_tables
ORDER BY schema_name, table_name
\\gexec

SELECT format('GRANT USAGE, SELECT ON SEQUENCE %I.%I TO %I', seq_ns.nspname, seq.relname, :'p0_5_app_role')
FROM pg_class seq
JOIN pg_namespace seq_ns ON seq_ns.oid = seq.relnamespace
JOIN pg_depend dep ON dep.objid = seq.oid AND dep.deptype = 'a'
JOIN pg_class tbl ON tbl.oid = dep.refobjid
JOIN pg_namespace tbl_ns ON tbl_ns.oid = tbl.relnamespace
JOIN p0_5_app_grant_tables targets ON targets.schema_name = tbl_ns.nspname AND targets.table_name = tbl.relname
WHERE seq.relkind = 'S'
ORDER BY seq_ns.nspname, seq.relname
\\gexec

SELECT (
  rolcanlogin = true
  AND rolsuper = false
  AND rolcreatedb = false
  AND rolcreaterole = false
  AND rolreplication = false
  AND rolbypassrls = false
)::int AS p0_5_app_role_safe_ok
FROM pg_roles
WHERE rolname = :'p0_5_app_role' \\gset

\\if :p0_5_app_role_safe_ok
\\else
\\echo 'FATAL: P0.5 app role must be LOGIN, non-superuser, non-createrole, and NOBYPASSRLS.'
SELECT 1 / 0 AS p0_5_abort;
\\endif

-- MUST use pg_has_role(...) here, NOT a raw one-hop pg_auth_members lookup: pg_has_role follows the
-- FULL transitive membership chain, so it also catches e.g. app_role -> some_intermediary_role ->
-- owner_role, which a direct pg_auth_members row check would miss (it only sees a DIRECT grant and
-- would report "safe" even though the app role could still assume owner/migrator privileges through
-- an intermediary). Same fix/rationale as deploy/postgres/p0-5b-role-split-staff-patient.sql's
-- app_patient/app_staff assertion (docs/_TODO/SAAS_FOUNDATION/LOG.md, taskdb #655/#662).
SELECT (
  NOT pg_has_role(:'p0_5_app_role', :'p0_5_owner_role', 'MEMBER')
  AND NOT pg_has_role(:'p0_5_app_role', :'p0_5_migrator_role', 'MEMBER')
)::int AS p0_5_app_membership_safe_ok \\gset

\\if :p0_5_app_membership_safe_ok
\\else
\\echo 'FATAL: P0.5 app role must not be a member of owner or migrator roles.'
SELECT 1 / 0 AS p0_5_abort;
\\endif

\\echo 'P0.5 role split UP complete.'
\\endif
`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  process.stdout.write(renderP05RoleSplitSql());
}
