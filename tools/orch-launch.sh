#!/usr/bin/env bash
# Порт запуска исполнителей и аудиторов. Мимо него агентов не запускать.
#
# Зачем: правила оркестрации (независимый аудит после каждого воркера, потолок агентов,
# актуальная база клона) лежали в AGENTS.md и docs/ORCHESTRATION_BINDINGS.md и всё равно
# нарушались — оркестратор их не перечитывал. Владелец 28.07: «если бы опирался на правила
# репо — оркестрация шла бы обязательно с аудированием». Поэтому правило переехало из памяти
# в дверь: скрипт ОТКАЗЫВАЕТ, если условия не выполнены.
#
# Использование:
#   tools/orch-launch.sh worker  <клон> <run-id> <модель> <effort> <файл-брифа> <слой-плана>
#   tools/orch-launch.sh auditor <клон> <run-id> <модель> <effort> <файл-брифа> <слой-плана>
#
#   <клон> — имя каталога рядом с репозиторием: bcb-wt-<имя> передаётся как <имя>.
#   Для короткоживущего автоматизированного shell/exec ставьте ORCH_WAIT=1: launcher дождётся
#   agent-run и вернёт его exit code. Без флага сохраняется обычный фоновый запуск из терминала.
#
# Проверки перед запуском (любая непройденная = отказ, exit 1):
#   1. Потолок одновременных агентов (AGENTS.md §24: ориентир 3).
#   2. Клон существует, дерево чистое и стоит РОВНО на текущей голове feat-ветки.
#   3. Бриф существует и непустой. Продуктовая работа обязана ссылаться на план в docs/_TODO/; для
#      операционной (слить ветки, спасти коммит, CI) плана нет — запускай с ORCH_OPS="<причина>",
#      тогда authority = сам бриф (осознанно и логируемо), фейковый план не плодится.
#   3a. Бриф про поломки/fault injection/арбитров/аудит тестов запускается только ролью
#      auditor-live — обычный auditor физически не может внести поломку (М2, #1081).
#   3b. Бриф воркера обязан отсылать к правилам репозитория про тесты И называть строку плана,
#      дающую oracle (обход обоих — ORCH_NO_TESTS="<причина>").
#   4. Для worker: у предыдущего воркера того же клона зарегистрирован аудит в файле очереди
#      (ORCHESTRATION_BINDINGS.md:55 — самооценка исполнителя не засчитывается); если тот коммит был
#      тестовым (`test(...)`), строка вердикта обязана называть путь к отчёту поломок и число
#      непойманного/убитых (М2, #1081).
#   5. Аудитор запускается только read-only; воркер — только workspace-write.
set -euo pipefail

MAIN=/home/dev/dev-projects/BersonCareBot
FEAT=feat/doctor-ui-rebuild
QUEUE="$MAIN/docs/_TODO/NIGHT_WAVE_AUDIT_QUEUE_2026-07-28.md"
# Потолки разные по роли. Воркеров 4 — владелец 28.07: «воркеров можно в 4 ручья гнать (только тесты
# чтобы гнали по очереди)»; это поверх ориентира AGENTS.md §24 в 3. Сериализация тестов — не здесь,
# а мьютексом run-tests.sh, и требованием в брифе.
# Аудиторы только читают, конфликтовать им нечем — их 5. Владелец 28.07: «почему аудит идёт
# в ОДИН ПОТОК? уж тут то можно хоть в пять».
MAX_WORKERS=${ORCH_MAX_WORKERS:-4}
MAX_AUDITORS=${ORCH_MAX_AUDITORS:-5}
PORT=/home/dev/brain/host-orch/agent-run.mjs

die() { echo "ОТКАЗ: $*" >&2; exit 1; }

[ $# -eq 7 ] || die "нужно 7 аргументов, дано $#. Смотри шапку файла."
ROLE=$1 CLONE_NAME=$2 RUN_ID=$3 MODEL=$4 EFFORT=$5 BRIEF=$6 PLAN_SLICE=$7
CLONE="/home/dev/dev-projects/bcb-wt-$CLONE_NAME"

# Владелец 28.07: «запускай аудиторов не в песочнице — это двойная работа и тупо».
# Причина, найденная в коде порта: роль `auditor` входит в READ_ONLY_ROLES
# (governor/host-sandbox.mjs:13), поэтому аудитору ПРИНУДИТЕЛЬНО ставится read-only-джейл
# независимо от того, что просит вызывающий. Джейл блокирует sudo, аудиторы не могли читать
# живую базу и честно ставили UNPROVEN — а перепроверял потом лид руками, то есть работа
# делалась дважды.
#
# Отсюда третья роль `auditor-live`: в порт уходит как worker (песочница пускает к базе), в
# потолках считается аудитором, а бриф ей ЗАПРЕЩАЕТ менять файлы. Гарантия не в песочнице, а в
# проверке после прогона: дерево клона обязано остаться чистым (напоминание печатается ниже).
ROLE_FOR_PORT="$ROLE"
case "$ROLE" in
  worker)       SANDBOX=workspace-write ;;
  auditor)      SANDBOX=read-only ;;
  auditor-live) SANDBOX=workspace-write; ROLE_FOR_PORT=worker ;;
  *) die "роль должна быть worker, auditor или auditor-live, дано '$ROLE'" ;;
esac

# 1. Потолок агентов.
LIVE_W=$(ps -eo args | grep '[a]gent-run\.mjs' | grep -c -- '--role worker' || true)
LIVE_A=$(ps -eo args | grep '[a]gent-run\.mjs' | grep -c -- '--role auditor' || true)
# auditor-live уходит в порт воркером, поэтому в счётчике воркеров он неотличим: считаем его
# аудитором консервативно — иначе один и тот же процесс не попадёт ни в один потолок.
[ "$ROLE" != auditor-live ] || LIVE_A=$((LIVE_A + LIVE_W))
if [ "$ROLE" = worker ]; then
  [ "$LIVE_W" -lt "$MAX_WORKERS" ] || die "уже $LIVE_W воркеров, потолок $MAX_WORKERS (AGENTS.md §24). В очередь, не веером."
  LIVE=$LIVE_W; CAP=$MAX_WORKERS
else
  [ "$LIVE_A" -lt "$MAX_AUDITORS" ] || die "уже $LIVE_A аудиторов, потолок $MAX_AUDITORS. В очередь."
  LIVE=$LIVE_A; CAP=$MAX_AUDITORS
fi

# 2. Клон: существует, чистый, на текущей голове feat.
[ -d "$CLONE/.git" ] || die "клон $CLONE не найден"
[ -z "$(git -C "$CLONE" status --porcelain)" ] || die "в клоне $CLONE есть незакоммиченное — салважни или сбрось перед запуском"
HEAD_MAIN=$(git -C "$MAIN" rev-parse "$FEAT")
HEAD_CLONE=$(git -C "$CLONE" rev-parse HEAD)
# Клон обязан СОДЕРЖАТЬ голову feat. Равенства требовать нельзя: клон с невлитым фиксом
# опережает feat на свой коммит, и его как раз надо аудировать (гейт 28.07 это запрещал —
# ошибка конструкции, найденная на первом же аудите фиксов).
if ! git -C "$CLONE" merge-base --is-ancestor "$HEAD_MAIN" "$HEAD_CLONE" 2>/dev/null; then
  die "клон $CLONE_NAME на ${HEAD_CLONE:0:9} НЕ содержит голову $FEAT ${HEAD_MAIN:0:9}. Сначала:
    git -C $CLONE fetch $MAIN $FEAT && git -C $CLONE merge --no-edit FETCH_HEAD
  (аудит на устаревшем клоне 28.07 проверял код, которого там не было)"
fi
AHEAD=$(git -C "$CLONE" rev-list --count "$HEAD_MAIN".."$HEAD_CLONE")

# 3. Бриф: есть, непустой. Authority: для продуктовой работы — ссылка на план в docs/_TODO/; для
#    операционной (слить ветки, спасти коммит, прогнать CI) плана нет и не должно быть — тогда
#    authority = сам бриф, а ORCH_OPS="<причина>" делает выбор осознанным и логируемым.
#    Владелец 29.07: «orch-launch механически требует docs/_TODO/ — некорректное решение хорошей идеи»;
#    хорошая идея (без authority нечего сдавать/проверять) сохранена, но перестала плодить фейковые планы
#    на «подмести пол».
[ -s "$BRIEF" ] || die "бриф $BRIEF не найден или пуст"
if [ -n "${ORCH_OPS:-}" ]; then
  echo "  ops-режим: authority = сам бриф; причина: $ORCH_OPS (план docs/_TODO/ не требуется)"
else
  grep -q "docs/_TODO/" "$BRIEF" || die "в брифе нет ссылки на план-файл в docs/_TODO/ — исполнителю нечего сдавать, аудитору нечего проверять (ORCHESTRATION_BINDINGS.md §{PROMPT_CONTEXT}).
  Продуктовая работа обязана ссылаться на план. Операционная (слить ветки/спасти коммит/CI) — запускай с
  ORCH_OPS=\"<причина>\", тогда authority = сам бриф."
fi

# 3a. Аудит тестов — только ролью auditor-live (М2, #1081). Владелец 31.07: роль арбитра/аудитора
#     поломок передаётся аудитору, а не автору теста — но обычный `auditor` уходит в read-only
#     песочницу и физически не может внести поломку в продуктовый код (governor/host-sandbox.mjs:13).
#     Так первый аудит уровня 2 интегратора выдал предсказания по чтению кода вместо реальных
#     прогонов с внесённой поломкой. Триггер — упоминание в брифе поломок/fault injection/арбитров/
#     аудита тестов; ролью запуска в этом случае обязана быть auditor-live. Обхода нет: если роль
#     действительно read-only-ревью без внесения поломок, не упоминай эти слова в брифе.
#     М2 круг 2 (#1081, M2-6 слепого аудита): список подстрок обходился синонимами того же смысла
#     («дефект», «инъекция ошибок», «мутации кода вручную» вместо буквального «поломки»/«аудит
#     тестов») — обычный auditor с таким брифом уходил в read-only песочницу необнаруженным.
#     Список расширен стемами синонимов и морфологией («поломк»→«полом», ловит и «поломок»).
#     Это по-прежнему список подстрок, не семантика — расширять при следующем обходе тем же путём.
if [ "$ROLE" = auditor ] && grep -qiE 'полом|fault.?injection|арбитр|аудит.?тест|дефект|инъекц|мутаци|внес.{0,20}ошиб|слепо.{0,20}список' "$BRIEF"; then
  die "бриф упоминает поломки/fault injection/арбитров/аудит тестов (или их синонимы — дефекты, инъекцию
  ошибок, мутации кода вручную), а роль запуска — обычный auditor.
  auditor уходит в read-only песочницу и физически не может внести поломку в продуктовый код —
  так первый аудит уровня 2 выдал предсказания по чтению кода вместо прогонов. Запускай ролью
  auditor-live (workspace-write, но бриф обязан запрещать ей менять файлы кроме внесения/откатывания
  поломки — дерево клона обязано остаться чистым после прогона)."
fi

# 3b. Бриф воркера обязан отсылать к правилам репозитория про тесты. Владелец 30.07: «как писать тесты — не забывай
#     давать агентам читать правила репо». Механика вместо памяти: без ссылки на правило исполнитель пишет тесты по
#     своему вкусу — так в этой же ветке появились фиктивные тесты на моках, которые оставались зелёными при удалении
#     колонок и полей. Обход — ORCH_NO_TESTS="<причина>" (например: чистое удаление, тесты не пишутся), он логируется.
if [ "$ROLE" = worker ] && [ -z "${ORCH_NO_TESTS:-}" ]; then
  grep -q "tests-check-behaviour-not-circumstances" "$BRIEF" || die "в брифе воркера нет ссылки на правила репозитория про тесты
  (.cursor/rules/tests-check-behaviour-not-circumstances.mdc, и обычно .cursor/rules/webapp-tests-lean-no-bloat.mdc).
  Без них исполнитель пишет тесты по своему вкусу: в этой ветке так появились тесты на моках, зелёные при удалении
  колонок. Если задача действительно без тестов — запускай с ORCH_NO_TESTS=\"<причина>\"."
  # 3b (продолжение, М2 #1081). Ссылки на правила недостаточно — воркер обязан знать, ОТКУДА взят
  # oracle ожидаемого поведения, а не только КАК не надо писать тесты. Проверяем явную пометку;
  # обход тот же ORCH_NO_TESTS.
  grep -q "Строка плана, дающая оракул" "$BRIEF" || die "в брифе воркера нет строки «Строка плана, дающая оракул:» —
  бриф ссылается на правила тестов, но не называет, ИЗ КАКОЙ СТРОКИ ПЛАНА взято ожидаемое поведение.
  Без неё исполнитель придумывает oracle сам, вместо того чтобы взять его из плана/решений владельца.
  Добавь в бриф явную строку вида «Строка плана, дающая оракул: <цитата/ссылка>». Если задача
  действительно без тестов — запускай с ORCH_NO_TESTS=\"<причина>\"."
  # 3b (продолжение 2, М2 круг 2 #1081, M2-5 слепого аудита): метка есть по форме, но раньше после
  # неё годился любой текст, включая «см. .cursor/rules/...» — план явно запрещает оракул как голую
  # ссылку на правила («а не только ссылку на правила»). Все реальные оракулы в этом репозитории
  # цитируют план в кавычках «…» (см. docs/_TODO/runs/testsuite-v2/*_BRIEF.md), и цитата часто
  # переносится markdown-абзацем на несколько строк (В9_ROLE_GUARDS_BRIEF.md:8-10) — поэтому берём
  # весь абзац от метки до первой пустой строки, а не только строку с самой меткой.
  ORACLE_BLOCK=$(awk '/Строка плана, дающая оракул/{f=1} f{print; if ($0 ~ /^[[:space:]]*$/) exit}' "$BRIEF" | tr '\n' ' ')
  printf '%s' "$ORACLE_BLOCK" | grep -qE '«.+»' || die "в брифе воркера есть строка «Строка плана, дающая оракул:»,
  но в абзаце после неё нет цитаты плана в кавычках «…» — план запрещает оракул как голую ссылку на правила
  (docs/_TODO/TEST_SUITE_AUDIT_2026-07-29.md, М2-5 слепого аудита: «см. .cursor/rules/...» без цитаты
  плана проходило раньше). Процитируй конкретную строку плана: «Строка плана, дающая оракул: <раздел> —
  «<дословная цитата>»». Если задача действительно без тестов — запускай с ORCH_NO_TESTS=\"<причина>\"."
fi
if [ -n "${ORCH_NO_TESTS:-}" ]; then
  echo "  без-тестов-режим: $ORCH_NO_TESTS"
fi

# 4. Для воркера: предыдущая работа этого клона должна быть зарегистрирована в очереди аудита.
if [ "$ROLE" = worker ]; then
  # Смотрим на СОБСТВЕННЫЕ коммиты клона (без коммитов слияния — их в очереди быть не может,
  # они появляются, когда в клон подтягивают свежий feat). Каждый обязан быть зарегистрирован
  # в файле очереди: либо он уже сведён, либо у него есть строка с вердиктом аудита.
  UNREG=""
  NO_ARTIFACT=""
  for sha in $(git -C "$CLONE" rev-list --no-merges "$HEAD_MAIN".."$HEAD_CLONE" 2>/dev/null); do
    short=${sha:0:9}
    if ! grep -q "$short" "$QUEUE"; then
      UNREG="$UNREG $short"
      continue
    fi
    # 4b (М2, #1081). Коммит тестовой работы (конвенция репо: `test(scope): ...`, см. 35eb9159c,
    # 7a7b24c08, 55cdfc48e, c223fcd15) обязан иметь в СВОЕЙ строке очереди путь к отчёту поломок
    # (.md/.json) и число непойманного/убитых — иначе PASS/FAIL в очереди ничем не доказан
    # (владелец 31.07: «без тестов не принимается аудит», тот же принцип применён к самой записи
    # вердикта). Формат не изобретаю — тот же, что уже используют записи очереди
    # (NIGHT_WAVE_AUDIT_QUEUE_2026-07-28.md): путь к артефакту + число рядом со словом
    # непойман*/убит*.
    subject=$(git -C "$CLONE" log --format=%s -1 "$sha")
    if printf '%s' "$subject" | grep -qE '^test\('; then
      line=$(grep "$short" "$QUEUE")
      if ! printf '%s' "$line" | grep -qiE '[A-Za-z0-9_./-]+\.(md|json)'; then
        NO_ARTIFACT="$NO_ARTIFACT $short(нет-пути-к-отчёту)"
      elif ! printf '%s' "$line" | grep -qiE '[0-9]+[^0-9]{0,20}(непойман|убит)|(непойман|убит)[^0-9]{0,20}[0-9]+'; then
        NO_ARTIFACT="$NO_ARTIFACT $short(нет-числа-непойманного/убитых)"
      fi
    fi
  done
  [ -z "$UNREG" ] || die "в клоне $CLONE_NAME есть несведённые коммиты без записи в $QUEUE:$UNREG
  Сначала аудит и строка с вердиктом в очереди, потом новая работа."
  [ -z "$NO_ARTIFACT" ] || die "в клоне $CLONE_NAME тестовые коммиты (test(...)) зарегистрированы в $QUEUE,
  но их строка вердикта не называет путь к отчёту поломок (.md/.json) и/или число непойманного/убитых:$NO_ARTIFACT
  Формат — как уже пишется в $QUEUE, новый не изобретай. Допиши строку вердикта, потом новая работа."
fi

# 5. Запуск. Лог рядом с брифом, run-id — в имени.
LOG="$(dirname "$BRIEF")/$RUN_ID.log"
echo "запуск: роль=$ROLE клон=$CLONE_NAME провайдер=${ORCH_PROVIDER:-codex} модель=$MODEL effort=$EFFORT слой=$PLAN_SLICE"
echo "  клон содержит feat ${HEAD_MAIN:0:9}, своих коммитов сверху: $AHEAD; агентов роли было $LIVE из $CAP; лог $LOG"
[ -z "${ORCH_DRY:-}" ] || { echo "  ORCH_DRY=1 — все проверки пройдены, агент НЕ запущен"; exit 0; }
# Провайдер по умолчанию — codex (весь исполнительский поток идёт через него). Владелец 30.07 попросил
# аудит плана ДВУМЯ моделями, Sol и Opus, поэтому провайдер стал параметром: ORCH_PROVIDER=claude.
# Мимо порта всё равно ничего не запускается — гейты выше не зависят от провайдера.
PROVIDER=${ORCH_PROVIDER:-codex}
# ORCH_JOB="worker|worker-hard|reviewer|reviewer-critical|explorer|mechanic" — канонический выбор модели и effort
# по карте `/home/dev/brain/docs/MODEL_TIERS.md`. Владелец 30.07: «у тебя же есть полный список решения когда и
# какого агента выбрать» — знание о цене и способностях живёт в одном месте, а не дублируется в каждом вызове.
# Если ORCH_JOB задан, модель и effort из аргументов ИГНОРИРУЮТСЯ (передавай в них job-имя дважды, для лога).
if [ -n "${ORCH_JOB:-}" ]; then
  MODEL_ARGS=(--job "$ORCH_JOB")
  echo "  job-режим: модель и effort выбирает канон по job=$ORCH_JOB (аргументы модели/effort игнорируются)"
else
  MODEL_ARGS=(--model "$MODEL" --effort "$EFFORT")
fi
nohup node "$PORT" --provider "$PROVIDER" "${MODEL_ARGS[@]}" \
  --role "$ROLE_FOR_PORT" --sandbox "$SANDBOX" --cwd "$CLONE" --run-id "$RUN_ID" \
  < "$BRIEF" > "$LOG" 2>&1 &
AGENT_PID=$!
echo "  pid=$AGENT_PID"
[ "$ROLE" != auditor-live ] || echo "  ⚠ auditor-live: после прогона проверить, что дерево клона осталось чистым"

# `nohup` защищает от SIGHUP обычного терминала, но не от lifecycle-cleanup короткоживущего
# automated exec-сеанса: тот удаляет оставшиеся дочерние процессы после выхода shell. Внешний
# bwrap порта запущен с --die-with-parent, поэтому вслед за agent-run исчезает и Codex, а run-state
# навсегда остаётся worker_running. Синхронный режим удерживает вызывающий сеанс до терминального
# состояния и сохраняет реальный код завершения порта.
if [ "${ORCH_WAIT:-}" = 1 ]; then
  echo "  ORCH_WAIT=1 — ждём завершения pid=$AGENT_PID"
  set +e
  wait "$AGENT_PID"
  AGENT_RC=$?
  set -e
  echo "  завершено: pid=$AGENT_PID rc=$AGENT_RC"
  exit "$AGENT_RC"
fi
