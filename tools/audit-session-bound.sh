#!/usr/bin/env bash
# Аудитор, ПРИВЯЗАННЫЙ К ЖИВОЙ СЕССИИ ЛИДА. Требование владельца 31.07:
#
#   «сделай так чтобы этот аудитор не запускался никаким портом автоматически, а если и запускался —
#    то получал ид сессии к которой запущен и механизм как ей писать. И точно самоубивался если
#    сессия стоит и больше не работает (например десктопный агент закончил: ид сессии ещё есть, а
#    работы в ней нет)».
#
# Почему это правило появилось: аудит роадмапа стоял в кроне на Codex/Sol и запускался раз в два часа
# сам по себе. Владелец Codex запретил (31.07), а сам аудит писал в собственный лог, которого никто не
# читал: за двое суток ни одна его находка не дошла ни до лида, ни до владельца, а последний прогон
# вообще оборвался по таймауту. Автономный аудитор без адресата — сожжённые токены и ложное чувство
# контроля.
#
# Что делает этот скрипт:
#   1. ОТКАЗЫВАЕТ без ид сессии и при несовпадении с текущей сессией лида.
#   2. ОТКАЗЫВАЕТ, если сессия не подаёт признаков жизни (метка старше порога).
#   3. Пишет находки ТУДА, ГДЕ ЛИД ИХ ЧИТАЕТ — в файл пробуждения (`runs/orch-wakeup.md`), который лид
#      разбирает на каждом ударе будильника. Это и есть «механизм как ей писать».
#   4. САМОУБИВАЕТСЯ на ходу: сторож в фоне следит за меткой сессии, и как только она протухает —
#      снимает агента. Сессия кончилась → аудит не доживает до конца, а не досчитывает в пустоту.
#
# Запуск только руками лида. В крон НЕ ставить: строка была удалена намеренно.
set -uo pipefail

ROOT=/home/dev/dev-projects/BersonCareBot
SESSION_FILE="$ROOT/runs/lead-session.id"
ALIVE_STAMP="$ROOT/runs/lead-alive.stamp"
WAKEUP="$ROOT/runs/orch-wakeup.md"
# Порог жизни: лид отмечается каждым ходом. Два пропущенных хода — уже не работа, а брошенная сессия.
ALIVE_MAX=${ALIVE_MAX:-1500}
WATCH_INTERVAL=${WATCH_INTERVAL:-60}

usage() {
  echo "использование: $0 <session-id> <файл-брифа> [модель] [effort]" >&2
  echo "  session-id обязателен и обязан совпадать с $SESSION_FILE" >&2
  exit 2
}

[ $# -ge 2 ] || usage
SESSION_ID=$1
BRIEF=$2
MODEL=${3:-claude-opus-5}
EFFORT=${4:-high}

# 1. Ид сессии обязателен и обязан быть ТЕКУЩИМ.
current=$(cat "$SESSION_FILE" 2>/dev/null || echo "")
if [ -z "$current" ]; then
  echo "ОТКАЗ: $SESSION_FILE пуст — живой сессии лида нет, аудитору некому докладывать." >&2
  exit 1
fi
if [ "$SESSION_ID" != "$current" ]; then
  echo "ОТКАЗ: передан ид сессии '$SESSION_ID', а текущая сессия лида '$current'." >&2
  echo "  Аудит, привязанный к чужой/прошлой сессии, пишет в пустоту — ровно то, что запрещено." >&2
  exit 1
fi

# 2. Сессия обязана подавать признаки жизни.
now=$(date +%s)
stamp=$(stat -c %Y "$ALIVE_STAMP" 2>/dev/null || echo 0)
age=$(( now - stamp ))
if [ "$stamp" = 0 ] || [ "$age" -gt "$ALIVE_MAX" ]; then
  echo "ОТКАЗ: сессия $SESSION_ID не подаёт признаков жизни ($age с назад, порог $ALIVE_MAX)." >&2
  echo "  Ид сессии есть, а работы в ней нет — это и есть случай, ради которого правило написано." >&2
  exit 1
fi

[ -s "$BRIEF" ] || { echo "ОТКАЗ: бриф '$BRIEF' пуст или не существует." >&2; exit 1; }

# Провайдер жёстко claude: Codex запрещён владельцем 31.07 («нет sol не трогай»). Здесь это не
# настройка, а константа — именно из-за этого места крон два дня гонял Sol.
RUN_ID="auditor-session-$(date +%Y%m%dT%H%M%S)"
LOG="$ROOT/runs/${RUN_ID}.log"

echo "аудит привязан к сессии $SESSION_ID (метка $age с назад), лог: $LOG"

nohup node /home/dev/brain/host-orch/agent-run.mjs \
  --provider claude --model "$MODEL" --effort "$EFFORT" \
  --role auditor --sandbox read-only --cwd "$ROOT" --run-id "$RUN_ID" \
  < "$BRIEF" >> "$LOG" 2>&1 &
AGENT_PID=$!
echo "  pid=$AGENT_PID"

# 4. Сторож самоубийства: пока агент жив, следим за меткой сессии. Протухла — снимаем агента и
#    оставляем строку в файле пробуждения, чтобы след не потерялся.
(
  while kill -0 "$AGENT_PID" 2>/dev/null; do
    sleep "$WATCH_INTERVAL"
    s=$(stat -c %Y "$ALIVE_STAMP" 2>/dev/null || echo 0)
    a=$(( $(date +%s) - s ))
    if [ "$s" = 0 ] || [ "$a" -gt "$ALIVE_MAX" ]; then
      kill "$AGENT_PID" 2>/dev/null
      {
        echo "- [ ] Аудит $RUN_ID снят сторожем $(date '+%F %H:%M'): сессия $SESSION_ID перестала"
        echo "      подавать признаки жизни (метка $a с назад). Докладывать было некому. Лог: $LOG"
      } >> "$WAKEUP"
      exit 0
    fi
  done
) >/dev/null 2>&1 &

wait "$AGENT_PID"
rc=$?

# 3. Механизм доклада: находки уходят в файл пробуждения, который лид читает на каждом ударе.
{
  echo "- [ ] Аудит $RUN_ID завершился (код $rc), сессия $SESSION_ID. Разобрать находки: $LOG"
} >> "$WAKEUP"

echo "аудит завершён, код $rc; строка добавлена в $WAKEUP"
exit "$rc"
