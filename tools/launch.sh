#!/usr/bin/env bash
# Обёртка над портом: синхронизирует клон с головой feat ПЕРЕД запуском.
#
# Зачем: голова feat двигается от каждого приземления и от каждой строки вердикта в очереди,
# поэтому между «подготовил клон» и «запустил» она успевает уехать, и порт отказывает
# «клон не содержит голову». За ночь так сгорело шесть запусков подряд. Синхронизация — не
# ослабление гейта: гейт требует, чтобы клон СОДЕРЖАЛ голову, и это ровно то, что делает merge.
# Отказ при грязном дереве сохраняется — там нужен салваж лидом, а не автослияние.
set -euo pipefail
MAIN=/home/dev/dev-projects/BersonCareBot
CLONE="/home/dev/dev-projects/bcb-wt-${2:?нужен клон вторым аргументом}"
[ -z "$(git -C "$CLONE" status --porcelain)" ] || { echo "ОТКАЗ: дерево $CLONE грязное — салважни сам" >&2; exit 1; }
git -C "$CLONE" fetch -q "$MAIN" feat/doctor-ui-rebuild
git -C "$CLONE" merge --no-edit -q FETCH_HEAD
exec "$MAIN/tools/orch-launch.sh" "$@"
